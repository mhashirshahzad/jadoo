void replaceEveryCharFromCurrentLevel(char oldCh, char newCh) {
  
  int i = 0, j = 0;
  for (; i <= currentLevelSize ; i++) {
    for (j = 0;j <= currentLevelSize; j++) {
      if (currentLevel[i][j] == oldCh) 
        currentLevel[i][j] = newCh;

    }
  }
}
void deleteEveryCharFromCurrentLevel(char ch) {
  int i = 0, j = 0;
  for (; i <= currentLevelSize ; i++) {
    for (j = 0;j <= currentLevelSize; j++) {
      if (currentLevel[i][j] == ch || currentLevel[i][j] == ch - 32) {
        currentLevel[i][j] = ' ';

        if (ch == 'g')
            spawnExplosion(i, j, ch, CONSOLE_BG_GREEN);
        else if (ch == 'b')
            spawnExplosion(i, j, ch, CONSOLE_BG_BLUE);
        else if (ch == 'v')
            spawnExplosion(i, j, ch, CONSOLE_BG_RED | CONSOLE_BG_BLUE);
      }
    }
  }
}
void deleteCharFromCurrentLevel(int yPos, int xPos, char ch) {
  currentLevel[yPos][xPos] = ' ';
}

void levelComplete(int &playerXPos, int &playerYPos) {
  changeCurrentLevel(levels[++currentLevelIndex], playerXPos, playerYPos);
}
void levelRestart(int &playerXPos, int &playerYPos) {
  changeCurrentLevel(levels[currentLevelIndex], playerXPos, playerYPos);
  
}

void changeCurrentLevel(char newLevel[100][100],int &playerXPos, int &playerYPos) {
  currentLevelSize = 0;
  int i = 0, j = 0;
  for (; i <= 100 && newLevel[i][0] != '\0'; i++) {
    for (j = 0;j <=100 && newLevel[i][j] != '\0'; j++) {
      currentLevel[i][j] = newLevel[i][j];
      if (newLevel[i][j] == '@') {
        playerXPos = j;
        playerYPos = i;
        currentLevel[i][j] = ' '; // player is drawn differently than other stuff
        
      }
    }

    if (j > currentLevelSize) {
      currentLevelSize = j;
    }
  }
  if (i > currentLevelSize) {
      currentLevelSize = i;
  }
}
